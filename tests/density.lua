-- Builds a representative window at a given density and runs the layout audit on every tab.
-- usage: getgenv().LGDensity = "Compact"; return loadstring(readfile("LiquidGlass/density.lua"))()
local Lib = loadstring(readfile("LiquidGlass/LiquidGlass.lua"))()
Lib._intro.Played = true
local W = Lib:CreateWindow({ Title = "Density " .. tostring(getgenv().LGDensity), Subtitle = "Layout audit", Icon = "ruler", Density = getgenv().LGDensity, Size = Vector2.new(720, 520) })
local A = W:AddTab({ Title = "Controls", Icon = "sliders" })
local s1 = A:AddSection("Switches")
s1:AddToggle({ Title = "Wi-Fi", Icon = "wifi", IconColor = Color3.fromRGB(10, 132, 255), Default = true })
s1:AddToggle({ Title = "Airplane Mode", Description = "Turns off every wireless connection", Icon = "airplane", IconColor = Color3.fromRGB(255, 159, 10) })
s1:AddToggle({ Title = "Small switch", Size = "Small" })
s1:AddToggle({ Title = "Large switch", Size = "Large", Default = true })
s1:AddSegmented({ Title = "Mode", Options = { "One", "Two", "Three" } })
s1:AddSegmented({ Options = { "Low", "High" } })
local s2 = A:AddSection("Values")
s2:AddSlider({ Title = "Speed", Default = 40 })
s2:AddSlider({ Title = "Time of day", Description = "With icon", Icon = "sun", IconColor = Color3.fromRGB(255, 159, 10), Default = 12, Max = 24 })
s2:AddSlider({ Title = "Large slider", Size = "Large", Default = 70 })
s2:AddStepper({ Title = "Count", Default = 3 })
s2:AddProgress({ Title = "Progress", Default = 0.5 })
local B = A:AddSection("Pickers")
B:AddDropdown({ Title = "Weapon", Options = { "Sword", "Bow" }, Default = "Sword", Icon = "target", IconColor = Color3.fromRGB(255, 69, 58) })
B:AddInput({ Title = "Name", Placeholder = "Type" })
B:AddKeybind({ Title = "Bind", Default = "F" })
B:AddColorPicker({ Title = "Color", Default = Color3.fromRGB(255, 45, 85) })
local C = W:AddTab({ Title = "Buttons", Icon = "grid" })
local s3 = C:AddSection("Buttons")
s3:AddButton({ Title = "Row button", Icon = "refresh", IconColor = Color3.fromRGB(142, 142, 147), Accessory = "Go" })
s3:AddButton({ Title = "Primary", Style = "Primary" })
s3:AddButton({ Title = "Small auto", Size = "Small", Width = "Auto" })
s3:AddButton({ Title = "Large", Size = "Large", Style = "Primary", Icon = "bolt" })
s3:AddButtons({ { Title = "A", Style = "Primary" }, { Title = "B" }, { Title = "C", Style = "Destructive" } })
s3:AddLabel("A label")
s3:AddParagraph({ Title = "Paragraph", Content = "Some longer text that wraps onto more than one line when the window gets narrow enough." })
task.wait(1.2)
local out = {}
for i = 1, #W.Tabs do
	W:SelectTab(i, true)
	task.wait(0.5)
	table.insert(out, (loadstring(readfile("LiquidGlass/layout.lua"))():gsub("\n$", "")))
end
W:SelectTab(1, true)
return table.concat(out, "\n")
